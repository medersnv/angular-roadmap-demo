import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const artifactsRoot = path.join(root, 'public/artifacts');
const outputPath = path.join(root, 'src/app/artifacts/artifacts.manifest.generated.ts');

function slug(title) {
  return title
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function collectFiles(dir, baseDir) {
  const files = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'README.md' || entry.name === 'manifest.json') {
      continue;
    }

    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...collectFiles(fullPath, baseDir));
      continue;
    }

    const relativePath = path.relative(baseDir, fullPath).split(path.sep).join('/');
    const stat = fs.statSync(fullPath);

    files.push({
      name: entry.name,
      relativePath,
      url: `artifacts/${path.relative(artifactsRoot, fullPath).split(path.sep).join('/')}`,
      size: stat.size,
      extension: path.extname(entry.name).slice(1).toLowerCase(),
      updatedAt: stat.mtime.toISOString(),
    });
  }

  return files.sort((a, b) => a.relativePath.localeCompare(b.relativePath));
}

const curriculumSource = fs.readFileSync(path.join(root, 'src/app/curriculum/curriculum.ts'), 'utf8');
const groups = [];
const groupRegex = /order:\s*(\d+),\s*title:\s*'([^']+)'/g;

for (const match of curriculumSource.matchAll(groupRegex)) {
  groups.push({ order: Number(match[1]), title: match[2] });
}

const categories = [
  {
    order: 0,
    slug: '00-general',
    title: 'Общие материалы',
    files: collectFiles(path.join(artifactsRoot, '00-general'), path.join(artifactsRoot, '00-general')),
  },
  ...groups.map((group) => {
    const categorySlug = `${String(group.order).padStart(2, '0')}-${slug(group.title)}`;
    const categoryDir = path.join(artifactsRoot, categorySlug);

    return {
      order: group.order,
      slug: categorySlug,
      title: group.title,
      files: fs.existsSync(categoryDir) ? collectFiles(categoryDir, categoryDir) : [],
    };
  }),
];

const manifest = {
  generatedAt: new Date().toISOString(),
  categories,
};

const fileContent = `/* eslint-disable */
/** Generated by scripts/generate-artifacts-manifest.mjs — do not edit manually */
import { ArtifactsManifest } from './artifacts.types';

export const ARTIFACTS_MANIFEST: ArtifactsManifest = ${JSON.stringify(manifest, null, 2)};
`;

fs.writeFileSync(outputPath, fileContent);

const totalFiles = categories.reduce((sum, category) => sum + category.files.length, 0);
console.log(`Wrote ${outputPath} (${totalFiles} files in ${categories.length} categories)`);
